def check_coordinator_branch_access(user, branch_ids: List[int]):
    """Ensure coordinator has role permissions for all requested branches."""
    if user.is_superuser or user.has_role(Role.Code.SUPER_ADMIN):
        return True

    user_branch_ids = set(
        user.role_assignments.filter(
            role__code=Role.Code.BRANCH_COORDINATOR
        ).values_list('branch_id', flat=True)
    )
    if not branch_ids:
        # Coordinator without specific branch ids must only operate on their assigned branches
        return True

    unauthorized = set(branch_ids) - user_branch_ids
    if unauthorized:
        raise PermissionDenied(
            detail=f"You do not have coordinator permissions for branches: {list(unauthorized)}."
        )
    return True


class GenerateTimetableAPIView(APIView):
    """
    POST /api/timetable/{version_id}/generate
    Initiates asynchronous automatic timetable generation using OR-Tools CP-SAT.
    """
    permission_classes = [IsBranchCoordinator]

    @extend_schema(
        request=GenerateTimetableInputSerializer,
        responses={
            202: OpenApiResponse(description="Generation task started"),
            400: OpenApiResponse(description="Invalid request"),
            403: OpenApiResponse(description="Permission denied"),
            404: OpenApiResponse(description="Version not found"),
        }
    )
    def post(self, request, version_id):
        try:
            schedule_version = ScheduleVersion.objects.get(id=version_id)
        except ScheduleVersion.DoesNotExist:
            raise NotFound(detail=f"Schedule version #{version_id} does not exist.")

        if schedule_version.status == ScheduleVersion.Status.PUBLISHED:
            raise ValidationError(detail="Cannot auto-schedule for a PUBLISHED schedule version.")
        if schedule_version.status == ScheduleVersion.Status.ARCHIVED:
            raise ValidationError(detail="Cannot auto-schedule for an ARCHIVED schedule version.")
        if schedule_version.status == ScheduleVersion.Status.UNDER_REVIEW:
            if not (request.user.is_superuser or request.user.has_role(Role.Code.SUPER_ADMIN)):
                raise PermissionDenied(detail="Schedule version is UNDER_REVIEW and can only be regenerated by Super Admins.")

        serializer = GenerateTimetableInputSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        branch_ids = serializer.validated_data.get('branch_ids') or []
        time_limit = serializer.validated_data.get('time_limit', 60)
        replace_existing = serializer.validated_data.get('replace_existing', False)

        # Validate coordinator branch permissions
        check_coordinator_branch_access(request.user, branch_ids)

        task_id = str(uuid.uuid4())
        update_task_progress(
            task_id=task_id,
            percentage=0,
            message="Queuing auto-scheduling background task...",
            version_id=version_id,
            branch_ids=branch_ids,
            time_limit=time_limit,
        )

        # Trigger Celery background task with synchronous fallback for dev/testing
        try:
            from django.conf import settings
            if getattr(settings, 'CELERY_TASK_ALWAYS_EAGER', False):
                generate_timetable.apply(
                    args=[version_id, branch_ids, time_limit, replace_existing, request.user.id],
                    task_id=task_id
                )
            else:
                generate_timetable.apply_async(
                    args=[version_id, branch_ids, time_limit, replace_existing, request.user.id],
                    task_id=task_id,
                    queue='scheduler'
                )
        except Exception as exc:
            logger.warning(f"Celery dispatch failed, running inline: {exc}")
            # Fallback to direct synchronous execution if Celery broker/worker is offline
            generate_timetable(
                version_id=version_id,
                branch_ids=branch_ids,
                time_limit=time_limit,
                replace_existing=replace_existing,
                user_id=request.user.id
            )

        return Response(
            {
                'task_id': task_id,
                'status': 'PENDING',
                'version_id': version_id,
                'message': 'Auto-scheduling background task initiated successfully.'
            },
            status=status.HTTP_202_ACCEPTED
        )


class TaskStatusAPIView(APIView):
    """
    GET /api/tasks/{task_id}/status
    Polls the progress percentage and outcome of a generation task.
    """
    permission_classes = [IsAuthenticated]

    @extend_schema(
        responses={
            200: TaskStatusResponseSerializer,
            404: OpenApiResponse(description="Task not found"),
        }
    )
    def get(self, request, task_id):
        # 1. Check cache first (Redis / LocMem)
        cached_info = cache.get(f"task_progress_{task_id}")
        if cached_info:
            return Response(cached_info, status=status.HTTP_200_OK)

        # 2. Check Celery AsyncResult if available
        try:
            from celery.result import AsyncResult
            res = AsyncResult(task_id)
            if res:
                task_state = res.state
                meta = res.info if isinstance(res.info, dict) else {}
                return Response(
                    {
                        'task_id': task_id,
                        'status': task_state,
                        'percentage': meta.get('percentage', 100 if task_state == 'SUCCESS' else 0),
                        'message': meta.get('message', f"Task is {task_state}"),
                        'proposal_id': meta.get('proposal_id'),
                        'error': str(res.result) if task_state == 'FAILURE' else None,
                    },
                    status=status.HTTP_200_OK
                )
        except Exception:
            pass

        raise NotFound(detail=f"Task #{task_id} not found or expired.")


class ProposalViewSet(viewsets.ReadOnlyModelViewSet):
    """
    GET /api/timetable/{version_id}/proposals
    GET /api/timetable/{version_id}/proposals/{id}
    Retrieves candidate auto-schedule proposals for a schedule version.
    """
    serializer_class = AutoScheduleProposalSerializer
    permission_classes = [IsAuthenticated]

    def get_queryset(self):
        version_id = self.kwargs.get('version_id')
        qs = AutoScheduleProposal.objects.select_related(
            'schedule_version', 'created_by'
        ).filter(schedule_version_id=version_id)

        status_param = self.request.query_params.get('status')
        if status_param:
            qs = qs.filter(status=status_param)
        return qs


class CommitProposalAPIView(APIView):
    """
    POST /api/timetable/{version_id}/commit-proposal
    Atomically commits a proposed schedule into live ScheduledMeeting & reservations.
    Re-validates all proposed placements against live state; returns 409 if conflict.
    """
    permission_classes = [IsBranchCoordinator]

    @extend_schema(
        request=CommitProposalInputSerializer,
        responses={
            200: OpenApiResponse(description="Proposal committed successfully"),
            400: OpenApiResponse(description="Invalid request or locked version"),
            404: OpenApiResponse(description="Proposal not found"),
            409: OpenApiResponse(description="Conflict detected during placement revalidation"),
        }
    )
    def post(self, request, version_id):
        try:
            schedule_version = ScheduleVersion.objects.get(id=version_id)
        except ScheduleVersion.DoesNotExist:
            raise NotFound(detail=f"Schedule version #{version_id} does not exist.")

        if schedule_version.status in [ScheduleVersion.Status.PUBLISHED, ScheduleVersion.Status.ARCHIVED]:
            raise ValidationError(detail=f"Cannot commit proposal to a {schedule_version.get_status_display()} schedule.")
        if schedule_version.status == ScheduleVersion.Status.UNDER_REVIEW:
            if not (request.user.is_superuser or request.user.has_role(Role.Code.SUPER_ADMIN)):
                raise PermissionDenied(detail="Schedule version is UNDER_REVIEW and cannot be modified by coordinators.")

        serializer = CommitProposalInputSerializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        proposal_id = serializer.validated_data['proposal_id']

        try:
            proposal = AutoScheduleProposal.objects.get(id=proposal_id, schedule_version=schedule_version)
        except AutoScheduleProposal.DoesNotExist:
            raise NotFound(detail=f"Proposal #{proposal_id} does not exist for version #{version_id}.")

        if proposal.status != AutoScheduleProposal.ProposalStatus.PENDING:
            raise ValidationError(detail=f"Proposal is already {proposal.get_status_display()} and cannot be re-committed.")

        check_coordinator_branch_access(request.user, proposal.selected_branches)

        replace_existing = proposal.generation_metadata.get('replace_existing', False)
        selected_branches = proposal.selected_branches

        with transaction.atomic():
            # If replacing existing, remove existing meetings for selected branches
            if replace_existing:
                existing_to_delete = ScheduledMeeting.objects.filter(
                    schedule_version=schedule_version
                )
                if selected_branches:
                    existing_to_delete = existing_to_delete.filter(
                        teaching_assignment__course_offering__cohort__branch_id__in=selected_branches
                    )
                for em in list(existing_to_delete):
                    TimetableReservationService.delete_meeting(
                        schedule_version=schedule_version,
                        meeting_id=em.id,
                        user=request.user
                    )

            # Re-validate every proposed meeting at commit time
            committed_meetings = []
            for m_data in proposal.proposed_meetings:
                assignment = TeachingAssignment.objects.select_related(
                    'course_offering__cohort__branch',
                    'course_offering__curriculum_item__course',
                    'professor'
                ).get(id=m_data['teaching_assignment_id'])
                room = Room.objects.get(id=m_data['room_id'])

                # Re-validate against authoritative constraints
                val_result = TimetableValidator.validate_meeting_placement(
                    schedule_version=schedule_version,
                    teaching_assignment=assignment,
                    weekday=m_data['weekday'],
                    start_slot=m_data['start_slot'],
                    duration_slots=m_data['duration_slots'],
                    room=room,
                    instruction_group_ids=m_data.get('instruction_group_ids'),
                    user=request.user,
                )

                if not val_result['allowed']:
                    # Conflict occurred! Roll back entire atomic transaction
                    conflict_msgs = "; ".join(c['message'] for c in val_result['conflicts'])
                    raise ConflictException(
                        detail={
                            'detail': f"Commit aborted: A conflict arose after schedule generation: {conflict_msgs}",
                            'conflicts': val_result['conflicts'],
                            'failed_meeting': m_data,
                        }
                    )

                # Save meeting & lock reservations
                saved_meeting = TimetableReservationService.save_meeting(
                    schedule_version=schedule_version,
                    teaching_assignment=assignment,
                    weekday=m_data['weekday'],
                    start_slot=m_data['start_slot'],
                    duration_slots=m_data['duration_slots'],
                    room=room,
                    instruction_group_ids=m_data.get('instruction_group_ids'),
                    user=request.user
                )
                committed_meetings.append(saved_meeting.id)

            # Mark proposal committed
            proposal.status = AutoScheduleProposal.ProposalStatus.COMMITTED
            proposal.save(update_fields=['status', 'updated_at'])

            # Increment schedule revision
            schedule_version.revision += 1
            schedule_version.save(update_fields=['revision', 'updated_at'])

        return Response(
            {
                'status': 'COMMITTED',
                'proposal_id': proposal.id,
                'version_id': version_id,
                'committed_meetings_count': len(committed_meetings),
                'message': f"Proposal #{proposal.id} successfully committed! {len(committed_meetings)} meetings scheduled."
            },
            status=status.HTTP_200_OK
        )


class DiscardProposalAPIView(APIView):
    """
    POST /api/timetable/{version_id}/discard-proposal
    Discards an auto-schedule proposal without altering the live timetable.
    """
    permission_classes = [IsBranchCoordinator]

    def post(self, request, version_id):
        proposal_id = request.data.get('proposal_id')
        if not proposal_id:
            raise ValidationError({'proposal_id': 'This field is required.'})

        try:
            proposal = AutoScheduleProposal.objects.get(
                id=proposal_id,
                schedule_version_id=version_id
            )
        except AutoScheduleProposal.DoesNotExist:
            raise NotFound(detail=f"Proposal #{proposal_id} not found.")

        check_coordinator_branch_access(request.user, proposal.selected_branches)

        proposal.status = AutoScheduleProposal.ProposalStatus.DISCARDED
        proposal.save(update_fields=['status', 'updated_at'])

        return Response(
            {
                'status': 'DISCARDED',
                'proposal_id': proposal.id,
                'message': f"Proposal #{proposal.id} discarded."
            },
            status=status.HTTP_200_OK
        )


class TimetableScoreAPIView(APIView):
    """
    GET /api/timetable/{version_id}/score
    Evaluates soft-constraint scores and quality report for a schedule version.
    """
    permission_classes = [IsAuthenticated]

    @extend_schema(responses={200: ScheduleScoreResponseSerializer})
    def get(self, request, version_id):
        try:
            schedule_version = ScheduleVersion.objects.get(id=version_id)
        except ScheduleVersion.DoesNotExist:
            raise NotFound(detail=f"Schedule version #{version_id} not found.")

        score_data = ScheduleScorer.evaluate_schedule_version(schedule_version)
        return Response(score_data, status=status.HTTP_200_OK)

